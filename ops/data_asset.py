"""Registers the generated cohort as a versioned data asset of the workspace, with its provenance in the tags."""

import argparse
import hashlib
import os
from datetime import UTC, datetime
from pathlib import Path

import pandas as pd
from azure.ai.ml import MLClient
from azure.ai.ml.constants import AssetTypes
from azure.ai.ml.entities import Data
from azure.identity import DefaultAzureCredential

from src.data.synthesize import DATA, LABEL, SEED

ASSET = "patient-cohort"


def workspace() -> MLClient:
    env = os.environ
    return MLClient(
        DefaultAzureCredential(), env["AZURE_SUBSCRIPTION_ID"], env["AZURE_RESOURCE_GROUP"], env["AML_WORKSPACE"]
    )


def register(client: MLClient, path: Path, version: str) -> Data:
    frame = pd.read_parquet(path)
    tags = {
        "rows": str(len(frame)),
        "features": str(len(frame.columns) - 2),
        "label": LABEL,
        "generator": "ctgan",
        "seed": str(SEED),
    }
    tags |= {
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "synthetic": "true",
        "readmission_rate": f"{frame[LABEL].mean():.3f}",
    }
    description = "Synthetic chronic-care cohort generated by src/data/synthesize.py; no real patient data."
    asset = Data(
        name=ASSET, version=version, path=str(path), type=AssetTypes.URI_FILE, description=description, tags=tags
    )
    registered: Data = client.data.create_or_update(asset)
    return registered


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", default=datetime.now(UTC).strftime("%Y.%m.%d"))
    parser.add_argument("--path", default=str(DATA / "cohort.parquet"))
    args = parser.parse_args()
    registered = register(workspace(), Path(args.path), args.version)
    tags = registered.tags or {}
    print(f"{registered.name}:{registered.version} rows={tags['rows']} sha256={tags['sha256'][:12]}")
